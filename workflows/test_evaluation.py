#!/usr/bin/env python3
"""Test Evaluation Workflow — Kai evaluates stats, Mara interprets UX impact.

Usage:
    python workflows/test_evaluation.py --data path/to/test_results.csv
    python workflows/test_evaluation.py --data path/to/test_results.csv --save "eval-pdp-size-guide.md"
"""

import argparse
from datetime import date
from pathlib import Path

import anthropic

# Adjust import path since this runs from workflows/
import sys
sys.path.insert(0, str(Path(__file__).parent.parent))

from agents import kai, mara

VAULT_PATH = Path.home() / "Desktop" / "MAIN" / "main_vault"


KAI_TASK = """Evaluate this A/B test. Follow your Mode 5 (Test Evaluation) process:
1. Check statistical significance (95% confidence minimum)
2. Analyze primary metric (CR or ARPU) AND secondary metrics
3. Segment the results — does it win everywhere, or only specific segments?
4. Check for novelty effects or time-based patterns
5. Calculate business impact in euros if possible
6. Recommend: ship, iterate, or kill

Be thorough but direct. Lead with the verdict."""


MARA_TASK = """Based on Kai's statistical evaluation of this A/B test, provide the UX interpretation:

1. **Why did this happen?** — What user behavior or psychological principle explains the result?
2. **Segment story** — If different segments responded differently, why might that be?
3. **What did we learn about our users?** — Regardless of win/loss, what does this tell us?
4. **Next hypothesis** — Based on this learning, what should we test next? Generate 1-2 hypothesis cards.
5. **Research gaps** — Is there anything we should investigate qualitatively before the next test?

Focus on the human story behind the numbers."""


def run_test_evaluation(client: anthropic.Anthropic, test_data: str, model: str = "claude-sonnet-4-6") -> str:
    """Run full test evaluation: Kai → Mara."""

    kai_agent = kai.create_agent(client, model=model)
    mara_agent = mara.create_agent(client, model=model)

    # Step 1: Kai evaluates the numbers
    print("📊 Kai is evaluating the test...")
    kai_result = kai.run(kai_agent, KAI_TASK, context=test_data)

    # Step 2: Mara interprets the findings
    print("🔬 Mara is interpreting the results...")
    mara_context = f"Test data:\n{test_data}\n\nKai's statistical evaluation:\n{kai_result}"
    mara_result = mara.run(mara_agent, MARA_TASK, context=mara_context)

    # Combine
    today = date.today().strftime("%Y-%m-%d")
    output = (
        f"# Test Evaluation — {today}\n\n"
        f"## 📊 Kai — Statistical Evaluation\n\n{kai_result}\n\n"
        f"---\n\n"
        f"## 🔬 Mara — UX Interpretation\n\n{mara_result}\n\n"
        f"---\n\n"
        f"*Generated by CJO Team (Kai + Mara)*"
    )

    return output


def main():
    parser = argparse.ArgumentParser(description="CJO Team — Test Evaluation Workflow")
    parser.add_argument("--data", "-d", required=True, help="Path to test results file")
    parser.add_argument("--model", "-m", default="claude-sonnet-4-6", help="Model for agents")
    parser.add_argument("--save", "-s", help="Save to vault with this filename")
    args = parser.parse_args()

    client = anthropic.Anthropic()
    test_data = Path(args.data).read_text(encoding="utf-8")

    result = run_test_evaluation(client, test_data, model=args.model)
    print(f"\n{result}")

    if args.save:
        output_dir = VAULT_PATH / "Ryzon" / "01_Projects" / "cjo-team-outputs"
        output_dir.mkdir(parents=True, exist_ok=True)
        path = output_dir / args.save
        path.write_text(result, encoding="utf-8")
        print(f"\n💾 Saved to: {path}")


if __name__ == "__main__":
    main()
